"""
Rebuild the premium / exposure spine so loss ratios mean something.

WHY
---
The inherited `premiums` table had 419,864 rows keyed on UUID policy ids with
zero overlap against `policies` (pol_00000...). Same orphaning as
underwriting_decisions: generated by a different run, never re-linked. Every
premium-to-policy join returned nothing, so no loss ratio could be computed by
product, channel, duration or underwriting cohort.

`policy_coverage` is orphaned the same way and is referenced by no code, so it
is left alone rather than rebuilt for its own sake.

WHAT THIS BUILDS
----------------
Monthly earned premium per policy, accrued across the policy's actual exposure
window. That is the correct construction rather than a convenience: earned
premium IS annual premium pro-rated by time at risk, which is exactly what
makes A/E-by-duration a meaningful cut. A single annual figure per policy
cannot support it.

Claim severities are then rescaled per line of business so incurred-to-earned
lands in a plausible range. Before this, Health ran at 244% and Investment at
6% -- claim amounts had been generated on a different scale from premiums, so
the ratio measured the generators' disagreement rather than anything about
risk. Relative variation between claims inside a line is preserved; only the
scale moves.

THE TARGETS ARE ASSUMPTIONS, NOT FINDINGS
-----------------------------------------
TARGET_LOSS_RATIO below is a set of plausible L&H figures chosen so the demo
behaves like a real book. They are an input to the synthetic data, not an
output of it. Nothing here is evidence about any real portfolio, and the A/E
screen says so on its face.

The leaked underwriting cohort still shows through, because it claims more
often and frequency is untouched by the rescaling -- the signal survives the
calibration rather than being manufactured by it.

Usage:
    venv\\Scripts\\python.exe database/seed_premium_spine.py
    venv\\Scripts\\python.exe database/seed_premium_spine.py --verify
"""
from __future__ import annotations

import argparse
import sys
from datetime import date
from pathlib import Path

import duckdb

SCRIPT_DIR = Path(__file__).resolve().parent
DB_PATH = str(SCRIPT_DIR / "insurance_v3.duckdb")

TODAY = date(2026, 8, 23)

# Plausible incurred-to-earned by line of business for a Singapore L&H book.
# Health carries medical inflation; investment-linked business is mostly
# savings with a thin protection rider, so its loss ratio is low by design.
TARGET_LOSS_RATIO = {
    "Health": 0.78,
    "Protection": 0.55,
    "Savings": 0.34,
    "Investment": 0.28,
}


def rebuild_premiums(con) -> None:
    print("[premiums] rebuilding monthly earned premium from policy exposure")

    before = con.execute("select count(*) from premiums").fetchone()[0]
    con.execute("DELETE FROM premiums")

    # Built entirely in SQL. Generating ~300k rows through executemany in Python
    # is what made the first spine rebuild take 50 minutes; generate_series and
    # a single INSERT..SELECT do the same work in seconds.
    con.execute(
        """
        INSERT INTO premiums (
          premium_id, policy_id, policy_coverage_id,
          premium_period_start, premium_period_end, transaction_date,
          transaction_type, written_premium_amount, earned_premium_amount,
          tax_fee_amount, created_at
        )
        WITH months AS (
          SELECT
            p.policy_id,
            p.annual_premium,
            UNNEST(generate_series(
              date_trunc('month', p.effective_date),
              least(coalesce(p.expiration_date, DATE '2026-08-23'), DATE '2026-08-23'),
              INTERVAL 1 MONTH
            )) AS period_start
          FROM policies p
          WHERE p.annual_premium IS NOT NULL AND p.annual_premium > 0
        )
        SELECT
          'prem_' || lpad(cast(row_number() OVER () AS VARCHAR), 8, '0'),
          policy_id,
          NULL,
          CAST(period_start AS DATE),
          CAST(period_start + INTERVAL 1 MONTH - INTERVAL 1 DAY AS DATE),
          CAST(period_start AS DATE),
          'earned',
          annual_premium / 12.0,
          annual_premium / 12.0,
          (annual_premium / 12.0) * 0.09,
          now()
        FROM months
        """
    )
    after = con.execute("select count(*) from premiums").fetchone()[0]
    joined = con.execute(
        "select count(*) from premiums pm join policies po on po.policy_id = pm.policy_id"
    ).fetchone()[0]
    print(f"           {before:,} orphaned rows replaced with {after:,} exposure-linked rows")
    print(f"           joined to a policy: {joined:,} / {after:,}")
    con.commit()


def rescale_claims(con) -> None:
    print("[claims] rescaling severities to plausible loss ratios by line of business")

    rows = con.execute(
        """
        with earned as (
          select pr.line_of_business as lob, sum(pm.earned_premium_amount) as earned
          from premiums pm
          join policies po on po.policy_id = pm.policy_id
          join products pr on pr.product_id = po.product_id
          group by 1
        ), incurred as (
          select pr.line_of_business as lob,
                 sum(c.paid_amount + c.reserve_amount) as incurred,
                 count(*) as n
          from claims c
          join policies po on po.policy_id = c.policy_id
          join products pr on pr.product_id = po.product_id
          group by 1
        )
        select e.lob, e.earned, coalesce(i.incurred, 0), coalesce(i.n, 0)
        from earned e left join incurred i on i.lob = e.lob
        """
    ).fetchall()

    factors = []
    for lob, earned, incurred, n in rows:
        target_lr = TARGET_LOSS_RATIO.get(lob)
        if not target_lr or not incurred or not earned:
            continue
        current_lr = incurred / earned
        factor = (target_lr * earned) / incurred
        factors.append((lob, factor))
        print(f"           {lob:<12} {n:>5} claims   LR {current_lr:>7.1%} -> {target_lr:>6.1%}   x{factor:.4f}")

    if not factors:
        print("           nothing to rescale")
        return

    con.execute("CREATE OR REPLACE TEMP TABLE _f (lob VARCHAR, factor DOUBLE)")
    con.executemany("INSERT INTO _f VALUES (?,?)", factors)
    con.execute(
        """
        UPDATE claims SET
          paid_amount = round(claims.paid_amount * f.factor, 2),
          reserve_amount = round(claims.reserve_amount * f.factor, 2)
        FROM policies po, products pr, _f f
        WHERE po.policy_id = claims.policy_id
          AND pr.product_id = po.product_id
          AND f.lob = pr.line_of_business
        """
    )
    con.commit()


def verify(con) -> bool:
    print("\n=== verification ===")
    ok = True

    joined = con.execute(
        "select count(*) from premiums pm join policies po on po.policy_id = pm.policy_id"
    ).fetchone()[0]
    total = con.execute("select count(*) from premiums").fetchone()[0]
    passed = total > 0 and joined == total
    ok = ok and passed
    print(f"  [{'PASS' if passed else 'FAIL'}] premium rows linked to a policy: {joined:,} / {total:,}")

    overall = con.execute(
        """
        select round(
          (select sum(paid_amount + reserve_amount) from claims) /
          nullif((select sum(earned_premium_amount) from premiums), 0), 4)
        """
    ).fetchone()[0]
    passed = overall is not None and 0.30 <= overall <= 0.95
    ok = ok and passed
    print(f"  [{'PASS' if passed else 'FAIL'}] overall incurred-to-earned: {overall:.1%} (want 30-95%)")

    print("\n  loss ratio by line of business:")
    for r in con.execute(
        """
        with earned as (
          select pr.line_of_business as lob, sum(pm.earned_premium_amount) as earned
          from premiums pm join policies po on po.policy_id = pm.policy_id
          join products pr on pr.product_id = po.product_id group by 1
        ), incurred as (
          select pr.line_of_business as lob, sum(c.paid_amount + c.reserve_amount) as incurred, count(*) as n
          from claims c join policies po on po.policy_id = c.policy_id
          join products pr on pr.product_id = po.product_id group by 1
        )
        select e.lob, round(e.earned) as earned, coalesce(i.n,0) as claims,
               round(coalesce(i.incurred,0)) as incurred,
               round(coalesce(i.incurred,0)/nullif(e.earned,0), 4) as lr
        from earned e left join incurred i on i.lob = e.lob order by lr desc
        """
    ).fetchall():
        print(f"    {r[0]:<12} earned S${r[1]:>12,.0f}  {r[2]:>5} claims  incurred S${r[3]:>11,.0f}  LR {r[4]:>7.1%}")

    print("\n  loss ratio by policy duration band (the axis A/E turns on):")
    for r in con.execute(
        """
        with earned as (
          select case when date_diff('month', po.effective_date, pm.premium_period_start) <= 12 then '01 0-12m'
                      when date_diff('month', po.effective_date, pm.premium_period_start) <= 24 then '02 13-24m'
                      else '03 25m+' end as band,
                 sum(pm.earned_premium_amount) as earned
          from premiums pm join policies po on po.policy_id = pm.policy_id group by 1
        ), incurred as (
          select case when c.policy_duration_months <= 12 then '01 0-12m'
                      when c.policy_duration_months <= 24 then '02 13-24m'
                      else '03 25m+' end as band,
                 sum(c.paid_amount + c.reserve_amount) as incurred, count(*) as n
          from claims c group by 1
        )
        select e.band, round(e.earned) as earned, coalesce(i.n,0) as claims,
               round(coalesce(i.incurred,0)/nullif(e.earned,0), 4) as lr
        from earned e left join incurred i on i.band = e.band order by e.band
        """
    ).fetchall():
        print(f"    {r[0]:<11} earned S${r[1]:>12,.0f}  {r[2]:>5} claims  LR {r[3]:>7.1%}")

    print("\n  loss ratio by underwriting rule version (does the leak show through?):")
    for r in con.execute(
        """
        with earned as (
          select ud.rule_id_applied as rule, sum(pm.earned_premium_amount) as earned
          from premiums pm
          join policies po on po.policy_id = pm.policy_id
          join underwriting_decisions ud on ud.application_id = po.application_id
          where ud.auto_decided = true
          group by 1
        ), incurred as (
          select ud.rule_id_applied as rule, sum(c.paid_amount + c.reserve_amount) as incurred, count(*) as n
          from claims c
          join policies po on po.policy_id = c.policy_id
          join underwriting_decisions ud on ud.application_id = po.application_id
          where ud.auto_decided = true
          group by 1
        )
        select e.rule, round(e.earned) as earned, coalesce(i.n,0) as claims,
               round(coalesce(i.incurred,0)/nullif(e.earned,0), 4) as lr
        from earned e left join incurred i on i.rule = e.rule order by e.rule
        """
    ).fetchall():
        print(f"    {r[0]:<16} earned S${r[1]:>12,.0f}  {r[2]:>5} claims  LR {r[3]:>7.1%}")

    print(f"\n=== {'ALL CHECKS PASSED' if ok else 'CHECKS FAILED'} ===")
    return ok


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--verify", action="store_true", help="checks only, no rebuild")
    args = ap.parse_args()

    con = duckdb.connect(DB_PATH, read_only=False)
    try:
        if not args.verify:
            rebuild_premiums(con)
            rescale_claims(con)
        return 0 if verify(con) else 1
    finally:
        con.close()


if __name__ == "__main__":
    sys.exit(main())
